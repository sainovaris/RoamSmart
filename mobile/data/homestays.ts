export function getHomestayById(id: string): Homestay | undefined {
  return HOMESTAYS.find((item) => item.id === id || item.slug === id);
}

export function formatNightlyPrice(homestay: Homestay): string {
  try {
    return new Intl.NumberFormat("en-IN", {
      style: "currency",
      currency: homestay.currency,
      maximumFractionDigits: 0,
    }).format(homestay.nightlyPrice);
  } catch {
    return `${homestay.currency} ${homestay.nightlyPrice}`;
  }
}
